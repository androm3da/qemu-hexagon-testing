use std::env;
use std::path::PathBuf;
use std::process::Command;

#[path = "pktgen/mod.rs"]
mod pktgen;

fn main() {
    println!("cargo::rustc-check-cfg=cfg(dma_layout_before_4)");
    let out_dir = PathBuf::from(env::var("OUT_DIR").unwrap());
    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let asm_dir = manifest_dir.join("asm");

    let clang = env::var("HEXAGON_CLANG").unwrap_or_else(|_| "hexagon-clang".to_string());
    let arch = env::var("HEXAGON_ARCH").unwrap_or_else(|_| "81".to_string());
    let march = format!("-mv{arch}");

    // Compile crt0.S
    let crt0_src = asm_dir.join("crt0.S");
    let crt0_obj = out_dir.join("crt0.o");

    let status = Command::new(&clang)
        .args([march.as_str(), "-G0", "-c", "-o"])
        .arg(&crt0_obj)
        .arg(&crt0_src)
        .status()
        .expect("Failed to run hexagon-clang");
    assert!(status.success(), "Failed to compile crt0.S");

    // Compile pte.S (TLB page table)
    let pte_src = asm_dir.join("pte.S");
    let pte_obj = out_dir.join("pte.o");

    let status = Command::new(&clang)
        .args([march.as_str(), "-G0", "-c", "-o"])
        .arg(&pte_obj)
        .arg(&pte_src)
        .status()
        .expect("Failed to run hexagon-clang");
    assert!(status.success(), "Failed to compile pte.S");

    // Packet-semantics tests: packets are assembled by the SDK assembler (not
    // rustc's bundled LLVM), one object per test binary.
    if env::var("CARGO_FEATURE_PKT").is_ok() {
        build_pkt_objects(&clang, &asm_dir, &out_dir);
    }

    // Linker script
    let linker_script = manifest_dir.join("hexagon.ld");
    println!("cargo:rustc-link-arg=-T{}", linker_script.display());

    // Tell cargo to link all object files
    println!("cargo:rustc-link-arg={}", crt0_obj.display());
    println!("cargo:rustc-link-arg={}", pte_obj.display());

    // Rerun if assembly, linker script, or toolchain path changes
    println!("cargo:rerun-if-changed=asm/crt0.S");
    println!("cargo:rerun-if-changed=asm/pte.S");
    println!("cargo:rerun-if-changed=hexagon.ld");
    println!("cargo:rerun-if-env-changed=HEXAGON_CLANG");
    println!("cargo:rerun-if-env-changed=HEXAGON_ARCH");
}

/// Names of the packet-semantics test binaries registered in Cargo.toml.
fn pkt_bins(manifest_dir: &std::path::Path) -> Vec<String> {
    let toml = std::fs::read_to_string(manifest_dir.join("Cargo.toml")).unwrap();
    let mut v = Vec::new();
    for line in toml.lines() {
        let line = line.trim();
        if let Some(rest) = line.strip_prefix("name = \"") {
            if let Some(name) = rest.strip_suffix('"') {
                if name.starts_with("test_pkt_") {
                    v.push(name.to_string());
                }
            }
        }
    }
    v
}

/// Assemble one packet source with the SDK toolchain.
fn assemble_pkt(clang: &str, arch: &str, inc: &std::path::Path, src: &std::path::Path, obj: &std::path::Path) {
    // HMX/HLX are only available through the SDK assembler (rustc's bundled
    // LLVM has neither), so every packet source is assembled here.
    let status = Command::new(clang)
        .args([&format!("-mv{arch}"), "-mhvx", "-mhmx", "-mhlx", "-G0", "-c", "-I"])
        .arg(inc)
        .arg("-o")
        .arg(obj)
        .arg(src)
        .status()
        .expect("Failed to run hexagon-clang");
    assert!(status.success(), "Failed to assemble {}", src.display());
}

/// Packet-semantics tests.  The packets are assembled by the SDK assembler
/// (not rustc's bundled LLVM): table-driven cases are generated by pktgen,
/// hand-written ones live in asm/pkt/<bin>.S.  Each object is linked into its
/// own binary only; the shared trampoline into all of them.
fn build_pkt_objects(clang: &str, asm_dir: &std::path::Path, out_dir: &std::path::Path) {
    let manifest_dir = asm_dir.parent().unwrap();
    let pkt_dir = asm_dir.join("pkt");
    // HLX needs v85; every packet object is assembled for it.
    let arch = env::var("HEXAGON_PKT_ARCH").unwrap_or_else(|_| "85".to_string());
    let bins = pkt_bins(manifest_dir);

    let shared_objs: Vec<std::path::PathBuf> = ["pkt_run", "pkt_vec"]
        .iter()
        .map(|n| {
            let obj = out_dir.join(format!("{n}.o"));
            assemble_pkt(clang, &arch, &pkt_dir, &pkt_dir.join(format!("{n}.S")), &obj);
            obj
        })
        .collect();

    let mut suites = pktgen::suites();
    // Debugging aid: PKT_CASE_FILTER=substr keeps only matching cases.
    if let Ok(f) = env::var("PKT_CASE_FILTER") {
        for s in &mut suites {
            s.cases.retain(|c| c.name.contains(&f));
        }
    }
    println!("cargo:rerun-if-env-changed=PKT_CASE_FILTER");
    println!("cargo:rerun-if-env-changed=PKT_MUTATE");
    println!("cargo:rerun-if-env-changed=PKT_STRICT");
    println!("cargo:rerun-if-env-changed=PKT_TRACE");
    println!("cargo:rerun-if-env-changed=PKT_MAX_REPORTS");
    for bin in &bins {
        for o in &shared_objs {
            println!("cargo:rustc-link-arg-bin={bin}={}", o.display());
        }
        // The workspace-wide -mv81 link arg comes first; a later -mv wins.
        println!("cargo:rustc-link-arg-bin={bin}=-mv{arch}");

        let hand = pkt_dir.join(format!("{bin}.S"));
        if hand.exists() {
            let obj = out_dir.join(format!("{bin}.hand.o"));
            assemble_pkt(clang, &arch, &pkt_dir, &hand, &obj);
            println!("cargo:rustc-link-arg-bin={bin}={}", obj.display());
        }
        if let Some(suite) = suites.iter().find(|s| s.name == bin.as_str()) {
            let (asm, tbl) = pktgen::emit(suite);
            let src = out_dir.join(format!("{bin}.gen.S"));
            std::fs::write(&src, asm).unwrap();
            std::fs::write(out_dir.join(format!("{bin}.tbl")), tbl).unwrap();
            let obj = out_dir.join(format!("{bin}.gen.o"));
            assemble_pkt(clang, &arch, &pkt_dir, &src, &obj);
            println!("cargo:rustc-link-arg-bin={bin}={}", obj.display());
        }
    }
    println!("cargo:rerun-if-changed=asm/pkt");
    println!("cargo:rerun-if-changed=pktgen");
    println!("cargo:rerun-if-changed=src/pkt/defaults.rs");
    println!("cargo:rerun-if-changed=Cargo.toml");
    println!("cargo:rerun-if-env-changed=HEXAGON_PKT_ARCH");
}
